# Merges data/firered_he/*.json ({"OFFSET_HEX": "hebrew"}) with the English source (_english.json)
# into data/translation_BPRE1.js, which the editor loads (works from file://).
# _english.json is extracted from your own ROM and is not in the repository (it is Nintendo's text): the pack keeps only
# an FNV-1a hash of each English line, which the editor checks against the ROM it opens.
import json, glob, os


def fnv(s):
    h = 0x811c9dc5
    for ch in s:
        h ^= ord(ch); h = (h * 0x01000193) & 0xffffffff
    return '%08x' % h


here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'data', 'firered_he')
english = {('%X' % e['o']): e['t'].replace('\n', '') for e in json.load(open(os.path.join(src, '_english.json'), encoding='utf-8'))}
pack, missing = {}, []
for f in sorted(glob.glob(os.path.join(src, 'b*.json'))):
    for k, he in json.load(open(f, encoding='utf-8')).items():
        k = k.upper()
        if k in english: pack[k] = [fnv(english[k]), he]
        else: missing.append(k)
out = os.path.join(here, '..', 'data', 'translation_BPRE1.js')
open(out, 'w', encoding='utf-8').write('// Generated by tools/build_translation.py - FireRed (US) v1.1 Hebrew translation\n'
    'window.TRANSLATIONS = window.TRANSLATIONS || {};\nwindow.TRANSLATIONS.BPRE1 = ' + json.dumps(pack, ensure_ascii=False) + ';\n')
# characters the game font can draw (see js/charmap.js); anything else would make the string fail to encode
import re
allowed = set("אבגדהוזחטיךכלםמןנסעףפץצקרשת0123456789 !?.,-…“”‘’'\"():;/&+=%$×♂♀éABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz״׳־▶<>")
bad = []
for k, (en, he) in pack.items():
    plain = re.sub(r'\{[^}]*\}|\\[nlp]', '', he)
    odd = set(c for c in plain if c not in allowed)
    if odd: bad.append(k + ' ' + ''.join(sorted(odd)))
print('strings:', len(pack), 'of', len(english), '| unknown keys:', missing[:10], '| bad chars:', bad[:20])
